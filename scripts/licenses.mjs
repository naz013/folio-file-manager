/** Texts that are the same for everyone, found among the packages that do ship one. */
const SHARED = {
  "MPL-2.0": /Mozilla Public License,? [Vv]ersion 2\.0/,
  "Apache-2.0": /Apache License\s+Version 2\.0/,
};

/**
 * The text for a package that ships no license file: the license's standard text with the
 * copyright holders the package names. Null when that cannot be made honestly, which fails
 * the check: a missing text is not waved through.
 */
function fallbackText(p, id, texts) {
  const note = `(${p.name} ships no license file. This is the standard ${id} text, with the authors the package lists.)\n\n`;
  // No author is invented: without names, the holder is "the authors" of the project's repository.
  const who =
    (p.authors ?? []).join(", ") || (p.repo ? `the authors of ${p.name} (${p.repo})` : "");
  if (SHARED[id]) {
    const found = Object.values(texts).find((t) => SHARED[id].test(t));
    return found ? note + found : null;
  }
  if (!who) return null;
  if (id === "MIT") return note + MIT(who);
  if (id === "BSD-3-Clause") return note + BSD(who, 3);
  if (id === "BSD-2-Clause") return note + BSD(who, 2);
  return null;
}

const idOf = (text) => createHash("sha256").update(text).digest("hex").slice(0, 12);

/** The list (without file paths) and the texts, shared by packages with the same text. */
export function collect(found) {
  const problems = [];
  const warnings = [];
  const texts = {};
  const missing = [];
  const packages = found.map((p) => {
    const verdict = judge(p.license);
    if (!verdict.ok)
      problems.push(`${p.name} ${p.version}: "${p.license}" (${verdict.problems.join(", ")})`);
    const text = licenseText(p.dir);
    const entry = {
      name: p.name,
      version: p.version,
      source: p.source,
      license: p.license,
      repo: p.repo,
      text: null,
    };
    if (text) {
      entry.text = idOf(text);
      texts[entry.text] = text;
    } else if (verdict.ok) {
      missing.push({ p, entry, id: verdict.ids[0] });
    }
    return entry;
  });
  // A second pass, so a shared text (MPL, Apache) can come from another package.
  for (const { p, entry, id } of missing) {
    const text = fallbackText(p, id, texts);
    if (!text) {
      problems.push(`${p.name} ${p.version}: ships no license file and none can be made for ${id}`);
      continue;
    }
    entry.text = idOf(text);
    texts[entry.text] = text;
    warnings.push(`${p.name} ${p.version}: no license file, the standard ${id} text is used`);
  }
  packages.sort((x, y) => x.name.localeCompare(y.name) || x.version.localeCompare(y.version));
  return { packages, texts, problems, warnings };
}

/** The installer's plain-text file: each distinct text once, with the packages it covers. */
export function plainText({ packages, texts }) {
  const groups = new Map();
  for (const p of packages) {
    const k = p.text ?? `none:${p.license}`;
    groups.set(k, [...(groups.get(k) ?? []), p]);
  }
  const parts = [
    "Folio is free software under the AGPL-3.0-only license (see LICENSE).",
    "It includes the following third-party software.",
  ];
  for (const [k, list] of groups) {
    const names = list.map((p) => `${p.name} ${p.version} (${p.license})`).join("\n");
    parts.push(
      `${"=".repeat(72)}\n${names}\n${"-".repeat(72)}\n${
        texts[k] ?? `License: ${list[0].license}. The package ships no license file.`
      }`,
    );
  }
  return parts.join("\n\n") + "\n";
}

function main() {
  const check = process.argv.includes("--check");
  const at = process.argv.indexOf("--target");
  const target = at > 0 ? process.argv[at + 1] : "x86_64-pc-windows-msvc";
  const { packages, texts, problems, warnings } = collect([...crates(target), ...npmPackages()]);
  for (const w of warnings) console.warn(`warning: ${w}`);
  if (problems.length) {
    console.error("These dependencies have a license that is unknown or not allowed:");
    for (const p of problems) console.error(`  ${p}`);
    console.error("Allowed licenses are listed in scripts/licenses-policy.mjs.");
    process.exit(1);
  }
  if (check) {
    console.log(`${packages.length} packages, all licenses allowed.`);
    return;
  }
  const data = { packages, texts };
  writeFileSync(join(root, "src", "lib", "licenses.json"), JSON.stringify(data) + "\n");
  writeFileSync(join(root, "src-tauri", "resources", "THIRD-PARTY-LICENSES.txt"), plainText(data));
  console.log(`${packages.length} packages, ${Object.keys(texts).length} license texts written.`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
