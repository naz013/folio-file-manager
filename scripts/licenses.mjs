// Collects the licenses of everything Folio ships (Rust crates and npm packages that end up in
// the app) from cargo and npm metadata, and fails if one is unknown or not allowed.
//
//   node scripts/licenses.mjs           writes the list the app shows and the installer's text file
//   node scripts/licenses.mjs --check   only judges, writes nothing
//   --target <triple>                   the platform shipped (default: Windows x64)
//
// Outputs: src/lib/licenses.json (read by the About dialog) and
// src-tauri/resources/THIRD-PARTY-LICENSES.txt (put next to the app by the installer).
// Both are committed as small stubs, and regenerated by CI and the release build.

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { judge } from "./licenses-policy.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const LICENSE_FILE = /^(licen[cs]e|copying|unlicense|notice)([-_.].*)?$/i;

/** The text of the license files in `dir`, joined, or "" when the package has none. */
function licenseText(dir) {
  if (!existsSync(dir)) return "";
  const names = readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && LICENSE_FILE.test(e.name) && !/\.(js|ts|json)$/i.test(e.name))
    .map((e) => e.name)
    .sort();
  return names
    .map((n) => readFileSync(join(dir, n), "utf8").replace(/\r\n/g, "\n").trim())
    .filter(Boolean)
    .join("\n\n---\n\n");
}

/** The Rust crates the app is built from: normal dependencies of the app, not dev or build ones. */
function crates(target) {
  const out = execFileSync(
    "cargo",
    [
      "metadata",
      "--format-version",
      "1",
      "--filter-platform",
      target,
      "--manifest-path",
      join(root, "src-tauri", "Cargo.toml"),
    ],
    { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 },
  );
  const meta = JSON.parse(out);
  const byId = new Map(meta.packages.map((p) => [p.id, p]));
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const seen = new Set();
  const stack = [meta.resolve.root];
  while (stack.length) {
    const id = stack.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const d of nodes.get(id)?.deps ?? []) {
      if (d.dep_kinds.some((k) => k.kind === null)) stack.push(d.pkg);
    }
  }
  seen.delete(meta.resolve.root);
  return [...seen].map((id) => {
    const p = byId.get(id);
    return {
      name: p.name,
      version: p.version,
      source: "crate",
      license: p.license ?? "",
      repo: p.repository ?? p.homepage ?? "",
      authors: p.authors ?? [],
      dir: dirname(p.manifest_path),
    };
  });
}

/** The npm packages in the app: the lock file's production tree. */
function npmPackages() {
  const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
  const out = [];
  for (const [key, entry] of Object.entries(lock.packages ?? {})) {
    // Optional packages are platform extras (pdf.js has a Node-only canvas): not in the app.
    if (!key || entry.dev || entry.optional) continue;
    const dir = join(root, key);
    if (!existsSync(join(dir, "package.json"))) {
      throw new Error(`${key} is in the lock file but not installed: run npm ci`);
    }
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    const old = Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type).join(" OR ") : "";
    const repo = typeof pkg.repository === "string" ? pkg.repository : (pkg.repository?.url ?? "");
    out.push({
      name: pkg.name,
      version: pkg.version,
      source: "npm",
      license: (typeof pkg.license === "string" ? pkg.license : pkg.license?.type) || old,
      repo: repo.replace(/^git\+/, "").replace(/\.git$/, ""),
      dir,
    });
  }
  return out;
}

